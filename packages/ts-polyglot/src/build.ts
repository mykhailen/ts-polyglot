// Turns a C, C++ or Rust file into a Node-API addon (.node) with one JavaScript function per
// exported native function, plus the ES module (.mjs) that loads the addon and exports those
// functions. Windows builds with MSVC, Linux and macOS with a gcc- or clang-compatible compiler:
// compiler.ts picks it and toolchain.ts runs it. Rust also needs rustc on PATH.
//
// C and C++: generated glue `#include`s the source file and wraps each function, so the glue sees
// the real declarations and C++ linkage just works. Rust: the file becomes a module of a small
// crate whose `extern "C"` wrappers are compiled to a static library, which the glue links.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { constants } from "node:os";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { resolveCompiler } from "./compiler.ts";
import { findFunctions, languageOf } from "./languages/index.ts";
import type { NativeFunction } from "./signatures.ts";
import { compileAddon, run, rustStaticLibName, rustTargetArgs } from "./toolchain.ts";

// Bump to rebuild every cached addon after changing the generated code or the compiler flags.
const GLUE_VERSION = 5;
// Linux and macOS bind an addon's symbols lazily, so a function the native file declares but never
// defines would kill node at its first call. RTLD_NOW fails the import instead, catchably. Windows
// has no dlopen flags; its linker already refuses such an addon.
const dlopenFlags: number | undefined = constants.dlopen.RTLD_NOW;
// TS_POLYGLOT_DEBUG=1 builds unoptimized addons with debug info (.pdb files on Windows), so a native
// debugger attached to node can stop in the C, C++ or Rust source.
const debug = process.env.TS_POLYGLOT_DEBUG === "1";
// TS_POLYGLOT_CACHE_DIR moves the cache: tests need a fresh one, and CI can keep one between runs.
const cacheRoot = process.env.TS_POLYGLOT_CACHE_DIR
  ? resolve(process.env.TS_POLYGLOT_CACHE_DIR)
  : fileURLToPath(new URL("../node_modules/.cache/ts-polyglot/", import.meta.url));

/** Builds the addon for a native file unless it's cached, and returns the path of the module that loads it. */
export function buildAddon(file: string, source: string): string {
  const language = languageOf(file);
  if (!language) throw new Error(`ts-polyglot: not a C, C++ or Rust file: ${file}`);
  const functions = findFunctions(source, language);
  // Rust's glue is C.
  const glueLanguage = language === "cpp" ? "cpp" : "c";
  const compiler = resolveCompiler(file, glueLanguage);
  // The platform is in the key because one checkout can be used from Windows and from WSL or a
  // container; the compiler, so that switching compilers rebuilds.
  const key = createHash("sha256")
    .update(JSON.stringify([GLUE_VERSION, debug, process.version, process.platform, process.arch, compiler.family === "msvc" ? "msvc" : compiler.command, language, source]))
    .digest("hex")
    .slice(0, 16);
  const dir = join(cacheRoot, key);
  const name = basename(file).replace(/\W/g, "_");
  const addon = join(dir, `${name}.node`);
  // Written after the addon, so it's there only when the build finished.
  const module = join(dir, `${name}.mjs`);
  if (existsSync(module)) return module;

  mkdirSync(dir, { recursive: true });
  const libs: string[] = [];
  let glue: string;
  if (language === "rust") {
    libs.push(...rustStaticLib(file, functions, dir, rustStaticLibName(compiler)));
    glue = join(dir, "glue.c");
    writeFileSync(glue, glueSource(functions, functions.map(rustPrototype).join("\n"), (fn) => `ts_polyglot__${fn.name}`));
  } else {
    glue = join(dir, language === "cpp" ? "glue.cpp" : "glue.c");
    writeFileSync(glue, glueSource(functions, `#include "${file.replaceAll("\\", "/")}"`, (fn) => fn.name));
  }
  compileAddon(compiler, { language: glueLanguage, glue, libs, out: addon, debug, cacheRoot });
  writeFileSync(module, moduleSource(file, addon, functions));
  return module;
}

/** The module an import of the native file resolves to. It's a file of its own so that it, not the native file, is what a JavaScript debugger sees. */
function moduleSource(file: string, addon: string, functions: NativeFunction[]): string {
  return [
    `// Generated by ts-polyglot: loads the addon built from ${file} and exports its functions.`,
    "const native = { exports: {} };",
    `process.dlopen(native, ${JSON.stringify(addon)}${dlopenFlags === undefined ? "" : `, ${dlopenFlags}`});`,
    ...functions.map((fn) => `export const ${fn.name} = native.exports.${fn.name};`),
    "",
  ].join("\n");
}

function glueSource(functions: NativeFunction[], prelude: string, callee: (fn: NativeFunction) => string): string {
  // The second comment is for whoever steps out of a native function in a debugger: this wrapper is
  // its caller, and past the wrapper is JavaScript, which a native debugger can't show.
  const lines = [
    "// Generated by ts-polyglot: one Node-API function per exported native function.",
    "// Stepping out of a native function lands here, in its caller. Beyond this wrapper is JavaScript,",
    "// which this debugger can't show: continue (F5) and the TypeScript debugger's step or breakpoint takes over.",
    "#include <stdbool.h>",
    "#include <stdint.h>",
    "#include <node_api.h>",
    prelude,
    "",
  ];
  for (const fn of functions) {
    const count = fn.params.length;
    lines.push(
      `static napi_value ts_polyglot__js_${fn.name}(napi_env env, napi_callback_info info) {`,
      `  size_t argc = ${count};`,
      `  napi_value argv[${Math.max(count, 1)}];`,
      "  napi_value result;",
      "  napi_get_cb_info(env, info, &argc, argv, NULL, NULL);",
      `  if (argc < ${count}) { napi_throw_type_error(env, NULL, "${fn.name}() expects ${count} argument(s)"); return NULL; }`,
    );
    fn.params.forEach((param, i) => {
      lines.push(
        `  ${param.kind.c} arg${i};`,
        `  if (${param.kind.fromJs}(env, argv[${i}], &arg${i}) != napi_ok) { napi_throw_type_error(env, NULL, "${fn.name}(): ${param.name} must be a ${param.kind.ts}"); return NULL; }`,
      );
    });
    const call = `${callee(fn)}(${fn.params.map((_, i) => `arg${i}`).join(", ")})`;
    if (fn.returns.ts === "void") lines.push(`  ${call};`, "  napi_get_undefined(env, &result);");
    else lines.push(`  ${fn.returns.toJs}(env, ${call}, &result);`);
    lines.push("  return result;", "}", "");
  }
  lines.push("NAPI_MODULE_INIT() {", "  napi_value fn;");
  for (const fn of functions) {
    lines.push(
      `  napi_create_function(env, "${fn.name}", NAPI_AUTO_LENGTH, ts_polyglot__js_${fn.name}, NULL, &fn);`,
      `  napi_set_named_property(env, exports, "${fn.name}", fn);`,
    );
  }
  lines.push("  return exports;", "}", "");
  return lines.join("\n");
}

function rustStaticLib(file: string, functions: NativeFunction[], dir: string, libName: string): string[] {
  const wrapper = join(dir, "wrapper.rs");
  writeFileSync(
    wrapper,
    [
      "#![allow(warnings)]",
      `#[path = ${JSON.stringify(file.replaceAll("\\", "/"))}]`,
      "mod user;",
      "",
      ...functions.map(rustWrapper),
    ].join("\n"),
  );
  const lib = join(dir, libName);
  const codegen = debug ? ["-C", "opt-level=0", "-C", "debuginfo=2"] : ["-C", "opt-level=2"];
  const args = ["--edition", "2021", "--crate-type", "staticlib", ...rustTargetArgs(process.platform, process.arch), ...codegen, "--print", "native-static-libs", "-o", lib, wrapper];
  const stderr = run("rustc", args, dir, { missing: "ts-polyglot: can't run rustc, which builds .rs files. Install Rust from https://rustup.rs." });
  // The library needs the system libraries Rust's standard library uses; rustc names them.
  const native = /native-static-libs:\s*(.*)/.exec(stderr)?.[1]?.trim().split(/\s+/) ?? [];
  return [lib, ...native];
}

/** `#[no_mangle] extern "C"` wrapper around a Rust function, using the C boundary types. */
function rustWrapper(fn: NativeFunction): string {
  const params = fn.params.map((p) => `${p.name}: ${p.kind.rust}`).join(", ");
  const args = fn.params.map((p) => (p.type === p.kind.rust ? p.name : `${p.name} as ${p.type}`)).join(", ");
  const call = `user::${fn.name}(${args})`;
  if (fn.returns.ts === "void") return `#[no_mangle]\npub extern "C" fn ts_polyglot__${fn.name}(${params}) {\n    ${call};\n}\n`;
  const body = fn.returnType === fn.returns.rust ? call : `${call} as ${fn.returns.rust}`;
  return `#[no_mangle]\npub extern "C" fn ts_polyglot__${fn.name}(${params}) -> ${fn.returns.rust} {\n    ${body}\n}\n`;
}

function rustPrototype(fn: NativeFunction): string {
  const params = fn.params.map((p, i) => `${p.kind.c} arg${i}`).join(", ") || "void";
  return `${fn.returns.c} ts_polyglot__${fn.name}(${params});`;
}
